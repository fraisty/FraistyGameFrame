using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;

namespace FRFrame.Editor
{
    /// <summary>
    /// UI 绑定代码生成器。
    /// 
    /// 生成内容：
    /// 1. 字段声明
    /// 2. BindInit 字段绑定
    /// 3. BindEvent 自动事件绑定
    /// 4. UnbindEvent 自动事件解绑
    /// 5. 常见 UGUI / TMP 控件事件包装方法
    /// 6. partial 业务回调方法声明
    /// 7. 常用 UI 辅助方法
    /// 8. 脚本 / 组件 enabled 控制方法
    /// 9. 绑定空值校验
    /// 
    /// 注意：
    /// 生成文件为 XXX.Bind.cs，请勿在生成文件里写业务逻辑。
    /// 业务逻辑请写在用户自己的 partial 类文件中。
    /// </summary>
    public static class UICodeGenerator
    {
        private sealed class GeneratedEventInfo
        {
            public string FieldName;
            public string EventName;
            public string AddLine;
            public string RemoveLine;
            public string WrapperName;
            public string PartialName;
            public string ParameterSignature;
            public string ParameterCall;
        }

        public static void Generate(UIBindData bindData, MonoScript explicitScript = null)
        {
            if (bindData == null)
            {
                Debug.LogError("UICodeGenerator.Generate failed, bindData is null.");
                return;
            }

            if (!ValidateBindData(bindData))
            {
                EditorUtility.DisplayDialog("错误", "绑定数据校验失败，请查看 Console。", "确定");
                return;
            }

            MonoScript script = explicitScript != null ? explicitScript : FindTargetMonoScript(bindData);
            if (script == null)
            {
                EditorUtility.DisplayDialog("错误", "未找到目标脚本，请先在 UIBindData 上指定 Target Script。", "确定");
                return;
            }

            Type targetType = script.GetClass();
            Debug.Log($"[UICodeGenerator] Target Script = {script.name}, Type = {targetType?.FullName}, Path = {AssetDatabase.GetAssetPath(script)}");
            if (targetType == null)
            {
                EditorUtility.DisplayDialog("错误", "目标脚本无法解析出类型。", "确定");
                return;
            }

            string scriptPath = AssetDatabase.GetAssetPath(script);
            string dir = Path.GetDirectoryName(scriptPath);
            string fileName = targetType.Name + ".Bind.cs";
            string outputPath = Path.Combine(dir ?? string.Empty, fileName);

            List<UIBindInfo> bindInfos = CreateBindInfos(bindData);
            UIBindEditorUtility.SortBindInfos(bindInfos, bindData);
            if (!HasSameOrder(bindData.BindInfos, bindInfos))
            {
                Undo.RecordObject(bindData, "Sort UI Bind Infos For Code Generation");
                bindData.SetBindInfos(bindInfos);
                EditorUtility.SetDirty(bindData);
            }

            string code = BuildCode(bindInfos, targetType);
            File.WriteAllText(outputPath, code, new UTF8Encoding(false));
            AssetDatabase.Refresh();

            Debug.Log($"UI Bind code generated : {outputPath}");
        }

        private static string BuildCode(List<UIBindInfo> bindInfos, Type targetType)
        {
            StringBuilder sb = new StringBuilder(16384);
            HashSet<string> usingSet = CollectUsingNamespaces(bindInfos, targetType);
            List<GeneratedEventInfo> eventInfos = CollectGeneratedEvents(bindInfos);

            AppendHeader(sb);
            AppendUsings(sb, usingSet);
            AppendNamespaceBegin(sb, targetType);

            string indent = string.IsNullOrEmpty(targetType.Namespace) ? "" : "    ";

            sb.AppendLine($"{indent}public partial class {targetType.Name}");
            sb.AppendLine($"{indent}{{");

            AppendFields(sb, bindInfos, eventInfos, indent);
            AppendBindInit(sb, bindInfos, targetType, indent);
            AppendBindEvent(sb, eventInfos, indent);
            AppendUnbindEvent(sb, eventInfos, indent);
            AppendValidateGeneratedBinds(sb, bindInfos, targetType, indent);
            AppendEventWrappersAndPartials(sb, eventInfos, indent);
            AppendWidgetBindPartials(sb, bindInfos, indent);
            AppendHelperMethods(sb, bindInfos, indent);

            sb.AppendLine($"{indent}}}");

            AppendNamespaceEnd(sb, targetType);

            return sb.ToString();
        }

        private static void AppendHeader(StringBuilder sb)
        {
            sb.AppendLine("// ==========================================================");
            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("// 此文件由 FRFrame UI 绑定工具自动生成，请勿手动修改。");
            sb.AppendLine("// 业务逻辑请写在另一个 partial 类文件中。");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine("// ==========================================================");
            sb.AppendLine();
        }

        private static void AppendUsings(StringBuilder sb, HashSet<string> usingSet)
        {
            List<string> list = new List<string>(usingSet);
            list.Sort(StringComparer.Ordinal);

            for (int i = 0; i < list.Count; i++)
            {
                if (!string.IsNullOrEmpty(list[i]))
                    sb.AppendLine($"using {list[i]};");
            }

            if (list.Count > 0)
                sb.AppendLine();
        }

        private static void AppendNamespaceBegin(StringBuilder sb, Type targetType)
        {
            string ns = targetType.Namespace;
            if (!string.IsNullOrEmpty(ns))
            {
                sb.AppendLine($"namespace {ns}");
                sb.AppendLine("{");
            }
        }

        private static void AppendNamespaceEnd(StringBuilder sb, Type targetType)
        {
            if (!string.IsNullOrEmpty(targetType.Namespace))
            {
                sb.AppendLine("}");
            }
        }

        private static void AppendFields(
            StringBuilder sb,
            List<UIBindInfo> bindInfos,
            List<GeneratedEventInfo> eventInfos,
            string indent)
        {
            sb.AppendLine($"{indent}    #region 自动生成字段");

            for (int i = 0; i < bindInfos.Count; i++)
            {
                UIBindInfo info = bindInfos[i];
                string fieldType = GetFieldTypeDisplayName(info);
                sb.AppendLine($"{indent}    protected {fieldType} {info.fieldName};");
            }

            if (eventInfos.Count > 0)
            {
                sb.AppendLine();
                sb.AppendLine($"{indent}    /// <summary>");
                sb.AppendLine($"{indent}    /// 自动生成事件是否已经绑定。");
                sb.AppendLine($"{indent}    /// 用于防止重复 AddListener。");
                sb.AppendLine($"{indent}    /// </summary>");
                sb.AppendLine($"{indent}    private bool _generatedEventsBound;");
            }

            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendBindInit(
            StringBuilder sb,
            List<UIBindInfo> bindInfos,
            Type targetType,
            string indent)
        {
            sb.AppendLine($"{indent}    #region 自动生成绑定初始化");
            sb.AppendLine($"{indent}    protected override void BindInit()");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        if (_bindData == null) return;");
            sb.AppendLine();

            for (int i = 0; i < bindInfos.Count; i++)
            {
                UIBindInfo info = bindInfos[i];
                string fieldType = GetFieldTypeDisplayName(info);

                if (info.isWidget)
                {
                    sb.AppendLine($"{indent}        {info.fieldName} = CreateWidget<{fieldType}>(_bindData.GetGameObjectByIndex({i}));");
                    sb.AppendLine($"{indent}        OnBind{ToPascalCase(info.fieldName)}({info.fieldName});");
                }
                else if (fieldType == "GameObject")
                {
                    sb.AppendLine($"{indent}        {info.fieldName} = _bindData.GetGameObjectByIndex({i});");
                }
                else
                {
                    sb.AppendLine($"{indent}        {info.fieldName} = _bindData.GetComponentByIndex<{fieldType}>({i});");
                }
            }

            sb.AppendLine();
            sb.AppendLine($"{indent}        ValidateGeneratedBinds();");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendBindEvent(
            StringBuilder sb,
            List<GeneratedEventInfo> eventInfos,
            string indent)
        {
            if (eventInfos.Count == 0)
                return;

            sb.AppendLine($"{indent}    #region 自动生成事件绑定");
            sb.AppendLine($"{indent}    protected override void BindEvent()");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        if (_generatedEventsBound) return;");
            sb.AppendLine($"{indent}        _generatedEventsBound = true;");
            sb.AppendLine();

            string currentField = null;
            for (int i = 0; i < eventInfos.Count; i++)
            {
                GeneratedEventInfo e = eventInfos[i];

                if (currentField != e.FieldName)
                {
                    if (currentField != null)
                        sb.AppendLine();

                    currentField = e.FieldName;
                    sb.AppendLine($"{indent}        if ({e.FieldName} != null)");
                    sb.AppendLine($"{indent}        {{");
                }

                sb.AppendLine($"{indent}            {e.AddLine}");

                bool nextSameField = i + 1 < eventInfos.Count && eventInfos[i + 1].FieldName == currentField;
                if (!nextSameField)
                {
                    sb.AppendLine($"{indent}        }}");
                }
            }

            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendUnbindEvent(
            StringBuilder sb,
            List<GeneratedEventInfo> eventInfos,
            string indent)
        {
            if (eventInfos.Count == 0)
                return;

            sb.AppendLine($"{indent}    #region 自动生成事件解绑");
            sb.AppendLine($"{indent}    protected override void UnbindEvent()");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}        if (!_generatedEventsBound) return;");
            sb.AppendLine($"{indent}        _generatedEventsBound = false;");
            sb.AppendLine();

            string currentField = null;
            for (int i = 0; i < eventInfos.Count; i++)
            {
                GeneratedEventInfo e = eventInfos[i];

                if (currentField != e.FieldName)
                {
                    if (currentField != null)
                        sb.AppendLine();

                    currentField = e.FieldName;
                    sb.AppendLine($"{indent}        if ({e.FieldName} != null)");
                    sb.AppendLine($"{indent}        {{");
                }

                sb.AppendLine($"{indent}            {e.RemoveLine}");

                bool nextSameField = i + 1 < eventInfos.Count && eventInfos[i + 1].FieldName == currentField;
                if (!nextSameField)
                {
                    sb.AppendLine($"{indent}        }}");
                }
            }

            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendValidateGeneratedBinds(
            StringBuilder sb,
            List<UIBindInfo> bindInfos,
            Type targetType,
            string indent)
        {
            sb.AppendLine($"{indent}    #region 自动生成绑定校验");
            sb.AppendLine($"{indent}    private void ValidateGeneratedBinds()");
            sb.AppendLine($"{indent}    {{");
            sb.AppendLine($"{indent}#if UNITY_EDITOR");

            // 用 (引用是否为空, 字段名) 数组循环校验，避免绑定数量多时生成大量重复的 if 行。
            sb.AppendLine($"{indent}        var __checks = new (bool isNull, string name)[]");
            sb.AppendLine($"{indent}        {{");

            for (int i = 0; i < bindInfos.Count; i++)
            {
                UIBindInfo info = bindInfos[i];
                sb.AppendLine($"{indent}            ({info.fieldName} == null, \"{info.fieldName}\"),");
            }

            sb.AppendLine($"{indent}        }};");
            sb.AppendLine($"{indent}        for (int __i = 0; __i < __checks.Length; __i++)");
            sb.AppendLine($"{indent}        {{");
            sb.AppendLine($"{indent}            if (__checks[__i].isNull)");
            sb.AppendLine($"{indent}                Debug.LogError($\"[{targetType.Name}] UI bind failed : {{__checks[__i].name}}\", this);");
            sb.AppendLine($"{indent}        }}");

            sb.AppendLine($"{indent}#endif");
            sb.AppendLine($"{indent}    }}");
            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendEventWrappersAndPartials(
            StringBuilder sb,
            List<GeneratedEventInfo> eventInfos,
            string indent)
        {
            if (eventInfos.Count == 0)
                return;

            sb.AppendLine($"{indent}    #region 自动生成事件包装方法");

            for (int i = 0; i < eventInfos.Count; i++)
            {
                GeneratedEventInfo e = eventInfos[i];

                sb.AppendLine($"{indent}    private void {e.WrapperName}({e.ParameterSignature})");
                sb.AppendLine($"{indent}    {{");

                if (string.IsNullOrEmpty(e.ParameterCall))
                    sb.AppendLine($"{indent}        {e.PartialName}();");
                else
                    sb.AppendLine($"{indent}        {e.PartialName}({e.ParameterCall});");

                sb.AppendLine($"{indent}    }}");
                sb.AppendLine();
            }

            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();

            sb.AppendLine($"{indent}    #region 自动生成业务回调 partial 方法声明");

            HashSet<string> methodKeys = new HashSet<string>();
            for (int i = 0; i < eventInfos.Count; i++)
            {
                GeneratedEventInfo e = eventInfos[i];
                string key = e.PartialName + "|" + e.ParameterSignature;
                if (!methodKeys.Add(key))
                    continue;

                sb.AppendLine($"{indent}    partial void {e.PartialName}({e.ParameterSignature});");
            }

            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendWidgetBindPartials(
            StringBuilder sb,
            List<UIBindInfo> bindInfos,
            string indent)
        {
            bool hasWidget = false;
            for (int i = 0; i < bindInfos.Count; i++)
            {
                if (bindInfos[i].isWidget)
                {
                    hasWidget = true;
                    break;
                }
            }

            if (!hasWidget)
                return;

            sb.AppendLine($"{indent}    #region 自动生成 Widget 绑定回调 partial 方法声明");

            for (int i = 0; i < bindInfos.Count; i++)
            {
                UIBindInfo info = bindInfos[i];
                if (!info.isWidget)
                    continue;

                string fieldType = GetFieldTypeDisplayName(info);
                sb.AppendLine($"{indent}    partial void OnBind{ToPascalCase(info.fieldName)}({fieldType} widget);");
            }

            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendHelperMethods(
            StringBuilder sb,
            List<UIBindInfo> bindInfos,
            string indent)
        {
            sb.AppendLine($"{indent}    #region 自动生成常用 UI 辅助方法");

            HashSet<string> generatedMethods = new HashSet<string>();

            for (int i = 0; i < bindInfos.Count; i++)
            {
                UIBindInfo info = bindInfos[i];
                if (info == null)
                    continue;

                Type t = ResolveBindInfoType(info);
                string fieldName = info.fieldName;
                string pascal = ToPascalCase(fieldName);

                if (string.IsNullOrEmpty(fieldName))
                    continue;

                // GameObject 显隐
                if (IsGameObjectType(t) || IsComponentType(t) || info.isWidget)
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Visible", $@"
    protected void Set{pascal}Visible(bool visible)
    {{
        if ({fieldName} != null)
            {GetGameObjectExpression(fieldName, t, info)}.SetActive(visible);
    }}");
                }

                if (IsEnableableComponentType(t))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Enabled", $@"
    protected void Set{pascal}Enabled(bool enabled)
    {{
        if ({fieldName} != null)
            {fieldName}.enabled = enabled;
    }}");
                }

                // Text / TMP_Text
                if (IsTypeOrSubclass(t, "UnityEngine.UI.Text") ||
                    IsTypeOrSubclass(t, "TMPro.TMP_Text"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Text", $@"
    protected void Set{pascal}Text(string value)
    {{
        if ({fieldName} != null)
            {fieldName}.text = value ?? string.Empty;
    }}");
                }

                // InputField / TMP_InputField
                if (IsTypeOrSubclass(t, "UnityEngine.UI.InputField") ||
                    IsTypeOrSubclass(t, "TMPro.TMP_InputField"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Text", $@"
    protected void Set{pascal}Text(string value)
    {{
        if ({fieldName} != null)
            {fieldName}.text = value ?? string.Empty;
    }}");

                    AppendUniqueMethod(generatedMethods, sb, indent, $"Get{pascal}Text", $@"
    protected string Get{pascal}Text()
    {{
        return {fieldName} != null ? {fieldName}.text : string.Empty;
    }}");
                }

                // Image
                if (IsTypeOrSubclass(t, "UnityEngine.UI.Image"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Sprite", $@"
    protected void Set{pascal}Sprite(Sprite sprite)
    {{
        if ({fieldName} != null)
            {fieldName}.sprite = sprite;
    }}");

                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Color", $@"
    protected void Set{pascal}Color(Color color)
    {{
        if ({fieldName} != null)
            {fieldName}.color = color;
    }}");
                }

                // RawImage
                if (IsTypeOrSubclass(t, "UnityEngine.UI.RawImage"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Texture", $@"
    protected void Set{pascal}Texture(Texture texture)
    {{
        if ({fieldName} != null)
            {fieldName}.texture = texture;
    }}");

                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Color", $@"
    protected void Set{pascal}Color(Color color)
    {{
        if ({fieldName} != null)
            {fieldName}.color = color;
    }}");
                }

                // Toggle
                if (IsTypeOrSubclass(t, "UnityEngine.UI.Toggle"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}IsOn", $@"
    protected void Set{pascal}IsOn(bool isOn, bool notify = true)
    {{
        if ({fieldName} == null) return;

        if (notify)
            {fieldName}.isOn = isOn;
        else
            {fieldName}.SetIsOnWithoutNotify(isOn);
    }}");
                }

                // Slider / Scrollbar
                if (IsTypeOrSubclass(t, "UnityEngine.UI.Slider") ||
                    IsTypeOrSubclass(t, "UnityEngine.UI.Scrollbar"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Value", $@"
    protected void Set{pascal}Value(float value, bool notify = true)
    {{
        if ({fieldName} == null) return;

        if (notify)
            {fieldName}.value = value;
        else
            {fieldName}.SetValueWithoutNotify(value);
    }}");
                }

                // Dropdown / TMP_Dropdown
                if (IsTypeOrSubclass(t, "UnityEngine.UI.Dropdown") ||
                    IsTypeOrSubclass(t, "TMPro.TMP_Dropdown"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Value", $@"
    protected void Set{pascal}Value(int value, bool notify = true)
    {{
        if ({fieldName} == null) return;

        if (notify)
            {fieldName}.value = value;
        else
            {fieldName}.SetValueWithoutNotify(value);
    }}");
                }

                // CanvasGroup
                if (IsTypeOrSubclass(t, "UnityEngine.CanvasGroup"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}CanvasVisible", $@"
    protected void Set{pascal}CanvasVisible(bool visible)
    {{
        if ({fieldName} == null) return;

        {fieldName}.alpha = visible ? 1f : 0f;
        {fieldName}.interactable = visible;
        {fieldName}.blocksRaycasts = visible;
    }}");

                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}Interactable", $@"
    protected void Set{pascal}Interactable(bool interactable)
    {{
        if ({fieldName} == null) return;

        {fieldName}.interactable = interactable;
        {fieldName}.blocksRaycasts = interactable;
    }}");
                }

                // RectTransform
                if (IsTypeOrSubclass(t, "UnityEngine.RectTransform"))
                {
                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}AnchoredPosition", $@"
    protected void Set{pascal}AnchoredPosition(Vector2 anchoredPosition)
    {{
        if ({fieldName} != null)
            {fieldName}.anchoredPosition = anchoredPosition;
    }}");

                    AppendUniqueMethod(generatedMethods, sb, indent, $"Set{pascal}SizeDelta", $@"
    protected void Set{pascal}SizeDelta(Vector2 sizeDelta)
    {{
        if ({fieldName} != null)
            {fieldName}.sizeDelta = sizeDelta;
    }}");
                }
            }

            sb.AppendLine($"{indent}    #endregion");
            sb.AppendLine();
        }

        private static void AppendUniqueMethod(
            HashSet<string> generatedMethods,
            StringBuilder sb,
            string indent,
            string methodName,
            string rawMethodCode)
        {
            if (!generatedMethods.Add(methodName))
                return;

            string[] lines = rawMethodCode.Trim('\r', '\n').Split(new[] { "\r\n", "\n" }, StringSplitOptions.None);
            for (int i = 0; i < lines.Length; i++)
            {
                sb.AppendLine(indent + lines[i]);
            }

            sb.AppendLine();
        }

        private static string GetGameObjectExpression(string fieldName, Type t, UIBindInfo info)
        {
            if (IsGameObjectType(t))
                return fieldName;

            return $"{fieldName}.gameObject";
        }

        private static List<GeneratedEventInfo> CollectGeneratedEvents(List<UIBindInfo> bindInfos)
        {
            List<GeneratedEventInfo> result = new List<GeneratedEventInfo>();

            for (int i = 0; i < bindInfos.Count; i++)
            {
                UIBindInfo info = bindInfos[i];
                if (info == null || info.isWidget)
                    continue;

                Type t = ResolveBindInfoType(info);
                if (t == null)
                    continue;

                AppendEventsForType(result, t, info.fieldName);
            }

            return result;
        }

        private static void AppendEventsForType(List<GeneratedEventInfo> list, Type type, string fieldName)
        {
            if (string.IsNullOrEmpty(fieldName))
                return;

            string pascal = ToPascalCase(fieldName);

            if (IsTypeOrSubclass(type, "UnityEngine.UI.Button"))
            {
                AddEvent(list, fieldName, "Click",
                    $"{fieldName}.onClick.AddListener(OnClick{pascal}Generated);",
                    $"{fieldName}.onClick.RemoveListener(OnClick{pascal}Generated);",
                    $"OnClick{pascal}Generated",
                    $"OnClick{pascal}",
                    "",
                    "");
                return;
            }

            if (IsTypeOrSubclass(type, "UnityEngine.UI.Toggle"))
            {
                AddEvent(list, fieldName, "ValueChanged",
                    $"{fieldName}.onValueChanged.AddListener(OnValueChanged{pascal}Generated);",
                    $"{fieldName}.onValueChanged.RemoveListener(OnValueChanged{pascal}Generated);",
                    $"OnValueChanged{pascal}Generated",
                    $"OnValueChanged{pascal}",
                    "bool value",
                    "value");
                return;
            }

            if (IsTypeOrSubclass(type, "UnityEngine.UI.Slider") ||
                IsTypeOrSubclass(type, "UnityEngine.UI.Scrollbar"))
            {
                AddEvent(list, fieldName, "ValueChanged",
                    $"{fieldName}.onValueChanged.AddListener(OnValueChanged{pascal}Generated);",
                    $"{fieldName}.onValueChanged.RemoveListener(OnValueChanged{pascal}Generated);",
                    $"OnValueChanged{pascal}Generated",
                    $"OnValueChanged{pascal}",
                    "float value",
                    "value");
                return;
            }

            if (IsTypeOrSubclass(type, "UnityEngine.UI.Dropdown") ||
                IsTypeOrSubclass(type, "TMPro.TMP_Dropdown"))
            {
                AddEvent(list, fieldName, "ValueChanged",
                    $"{fieldName}.onValueChanged.AddListener(OnValueChanged{pascal}Generated);",
                    $"{fieldName}.onValueChanged.RemoveListener(OnValueChanged{pascal}Generated);",
                    $"OnValueChanged{pascal}Generated",
                    $"OnValueChanged{pascal}",
                    "int value",
                    "value");
                return;
            }

            if (IsTypeOrSubclass(type, "UnityEngine.UI.InputField") ||
                IsTypeOrSubclass(type, "TMPro.TMP_InputField"))
            {
                AddEvent(list, fieldName, "ValueChanged",
                    $"{fieldName}.onValueChanged.AddListener(OnValueChanged{pascal}Generated);",
                    $"{fieldName}.onValueChanged.RemoveListener(OnValueChanged{pascal}Generated);",
                    $"OnValueChanged{pascal}Generated",
                    $"OnValueChanged{pascal}",
                    "string value",
                    "value");

                AddEvent(list, fieldName, "EndEdit",
                    $"{fieldName}.onEndEdit.AddListener(OnEndEdit{pascal}Generated);",
                    $"{fieldName}.onEndEdit.RemoveListener(OnEndEdit{pascal}Generated);",
                    $"OnEndEdit{pascal}Generated",
                    $"OnEndEdit{pascal}",
                    "string value",
                    "value");
                return;
            }

            if (IsTypeOrSubclass(type, "UnityEngine.UI.ScrollRect"))
            {
                AddEvent(list, fieldName, "ValueChanged",
                    $"{fieldName}.onValueChanged.AddListener(OnValueChanged{pascal}Generated);",
                    $"{fieldName}.onValueChanged.RemoveListener(OnValueChanged{pascal}Generated);",
                    $"OnValueChanged{pascal}Generated",
                    $"OnValueChanged{pascal}",
                    "Vector2 value",
                    "value");
            }
        }

