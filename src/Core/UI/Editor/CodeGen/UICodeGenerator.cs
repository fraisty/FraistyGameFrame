        private static List<UIBindInfo> CreateBindInfos(UIBindData bindData)
        {
            List<UIBindInfo> bindInfos = new List<UIBindInfo>();
            for (int i = 0; i < bindData.BindInfos.Count; i++)
            {
                if (bindData.BindInfos[i] != null)
                    bindInfos.Add(bindData.BindInfos[i]);
            }

            return bindInfos;
        }

        private static bool HasSameOrder(IReadOnlyList<UIBindInfo> current, List<UIBindInfo> sorted)
        {
            if (current == null || current.Count != sorted.Count)
                return false;

            for (int i = 0; i < current.Count; i++)
            {
                if (!ReferenceEquals(current[i], sorted[i]))
                    return false;
            }

            return true;
        }

        private static HashSet<string> CollectUsingNamespaces(List<UIBindInfo> bindInfos, Type targetType)
        {
            HashSet<string> set = new HashSet<string>();

            set.Add("UnityEngine");

            for (int i = 0; i < bindInfos.Count; i++)
            {
                UIBindInfo info = bindInfos[i];
                if (info == null)
                    continue;

                Type t = ResolveBindInfoType(info);
                if (t != null && !string.IsNullOrEmpty(t.Namespace))
                {
                    set.Add(t.Namespace);
                }
            }

            if (targetType.Namespace == "FRFrame")
            {
                set.Remove("FRFrame");
            }

            return set;
        }

        private static Type ResolveBindInfoType(UIBindInfo info)
        {
            if (info == null)
                return null;

            if (info.isWidget)
            {
                return UIBindEditorUtility.FindType(info.widgetTypeName);
            }

            return UIBindEditorUtility.FindType(info.typeName);
        }

        private static string GetFieldTypeDisplayName(UIBindInfo info)
        {
            Type t = ResolveBindInfoType(info);
            if (t != null)
            {
                return GetFriendlyTypeName(t);
            }

            if (info.isWidget && !string.IsNullOrEmpty(info.widgetTypeName))
            {
                int dot = info.widgetTypeName.LastIndexOf('.');
                return dot >= 0 ? info.widgetTypeName.Substring(dot + 1) : info.widgetTypeName;
            }

            if (string.IsNullOrEmpty(info.typeName))
                return "GameObject";

            int lastDot = info.typeName.LastIndexOf('.');
            return lastDot >= 0 ? info.typeName.Substring(lastDot + 1) : info.typeName;
        }

        private static string GetFriendlyTypeName(Type type)
        {
            if (type == null)
                return "object";

            if (!type.IsGenericType)
                return type.Name;

            string typeName = type.Name;
            int backtickIndex = typeName.IndexOf('`');
            if (backtickIndex >= 0)
                typeName = typeName.Substring(0, backtickIndex);

            Type[] args = type.GetGenericArguments();
            StringBuilder sb = new StringBuilder();
            sb.Append(typeName);
            sb.Append("<");
            for (int i = 0; i < args.Length; i++)
            {
                if (i > 0)
                    sb.Append(", ");

                sb.Append(GetFriendlyTypeName(args[i]));
            }
            sb.Append(">");
            return sb.ToString();
        }

        private static MonoScript FindTargetMonoScript(UIBindData bindData)
        {
            if (bindData.TargetScript != null && !string.IsNullOrEmpty(bindData.TargetScript.FullTypeName))
            {
                Type t = UIBindEditorUtility.FindType(bindData.TargetScript.FullTypeName);
                if (t != null)
                {
                    string[] guids = AssetDatabase.FindAssets($"t:MonoScript {t.Name}");
                    for (int i = 0; i < guids.Length; i++)
                    {
                        string path = AssetDatabase.GUIDToAssetPath(guids[i]);
                        MonoScript ms = AssetDatabase.LoadAssetAtPath<MonoScript>(path);
                        if (ms != null && ms.GetClass() == t)
                            return ms;
                    }
                }
            }

            return null;
        }

        private static bool ValidateBindData(UIBindData bindData)
        {
            bool valid = true;
            HashSet<string> fieldNames = new HashSet<string>();
            HashSet<string> bindingKeys = new HashSet<string>();

            for (int i = 0; i < bindData.BindInfos.Count; i++)
            {
                UIBindInfo info = bindData.BindInfos[i];
                if (info == null)
                {
                    Debug.LogError($"[UICodeGenerator] BindInfo null, index: {i}");
                    valid = false;
                    continue;
                }

                if (string.IsNullOrEmpty(info.fieldName))
                {
                    Debug.LogError($"[UICodeGenerator] FieldName empty, index: {i}");
                    valid = false;
                }
                else if (!fieldNames.Add(info.fieldName))
                {
                    Debug.LogError($"[UICodeGenerator] Duplicate fieldName: {info.fieldName}, index: {i}");
                    valid = false;
                }

                if (info.target == null)
                {
                    Debug.LogError($"[UICodeGenerator] Target null, field: {info.fieldName}, index: {i}");
                    valid = false;
                }

                if (info.isWidget)
                {
                    Type widgetType = UIBindEditorUtility.FindType(info.widgetTypeName);
                    if (widgetType == null)
                    {
                        Debug.LogError($"[UICodeGenerator] Widget type not found: {info.widgetTypeName}, field: {info.fieldName}");
                        valid = false;
                    }
                    else if (!UIBindEditorUtility.IsWidgetType(widgetType))
                    {
                        Debug.LogError($"[UICodeGenerator] Type is not UIWidget: {info.widgetTypeName}, field: {info.fieldName}");
                        valid = false;
                    }
                }
                else
                {
                    Type type = UIBindEditorUtility.FindType(info.typeName);
                    if (type == null)
                    {
                        Debug.LogError($"[UICodeGenerator] Bind type not found: {info.typeName}, field: {info.fieldName}");
                        valid = false;
                    }
                    else if (type != typeof(GameObject) && info.target != null)
                    {
                        Component component = UIBindEditorUtility.ResolveComponent(info.target, type);
                        if (component == null)
                        {
                            Debug.LogError($"[UICodeGenerator] Component missing: {type.Name}, target: {info.target.name}, field: {info.fieldName}");
                            valid = false;
                        }
                    }
                }

                string key = info.target != null
                    ? info.target.GetInstanceID() + "|" + (info.isWidget ? info.widgetTypeName : info.typeName)
                    : string.Empty;

                if (!string.IsNullOrEmpty(key) && !bindingKeys.Add(key))
                {
                    Debug.LogError($"[UICodeGenerator] Duplicate binding: {key}, field: {info.fieldName}");
                    valid = false;
                }
            }

            return valid;
        }

        private static bool IsGameObjectType(Type t)
        {
            return t == typeof(GameObject);
        }

        private static bool IsComponentType(Type t)
        {
            return t != null && typeof(Component).IsAssignableFrom(t);
        }

        private static bool IsEnableableComponentType(Type t)
        {
            return t != null && typeof(Behaviour).IsAssignableFrom(t);
        }

        private static bool IsTypeOrSubclass(Type type, string fullName)
        {
            if (type == null || string.IsNullOrEmpty(fullName))
                return false;

            Type current = type;
            while (current != null)
            {
                if (current.FullName == fullName)
                    return true;

                current = current.BaseType;
            }

            return false;
        }

        private static string ToPascalCase(string value)
        {
            if (string.IsNullOrEmpty(value))
                return string.Empty;

            StringBuilder sb = new StringBuilder(value.Length);
            bool upperNext = true;

            for (int i = 0; i < value.Length; i++)
            {
                char c = value[i];

                if (c == '_' || c == '-' || c == ' ')
                {
                    upperNext = true;
                    continue;
                }

                if (sb.Length == 0)
                {
                    sb.Append(char.ToUpperInvariant(c));
                    upperNext = false;
                    continue;
                }

                if (upperNext)
                {
                    sb.Append(char.ToUpperInvariant(c));
                    upperNext = false;
                }
                else
                {
                    sb.Append(c);
                }
            }

            return sb.ToString();
        }
